import * as z from "zod";
import { displayText, RunStateSchema } from "./entities.ts";
import {
  AgentIdSchema,
  CorrelationIdSchema,
  DeviceIdSchema,
  EventIdSchema,
  RepositoryIdSchema,
  RunIdSchema,
  UserIdSchema,
  WorkspaceIdSchema,
} from "./ids.ts";
import { canTransition, LIMITS, PROTOCOL_VERSION } from "./model.ts";

/**
 * Who caused an event. A client cannot choose its identity: the server binds
 * the actor to the authenticated connection before it relays or stores an
 * event (from M2), and only the server itself acts as `system`.
 */
export const ActorSchema = z.discriminatedUnion("kind", [
  z.object({ kind: z.literal("user"), userId: UserIdSchema }),
  z.object({ kind: z.literal("agent"), agentId: AgentIdSchema }),
  z.object({ kind: z.literal("system") }),
]);
export type Actor = z.infer<typeof ActorSchema>;

/** ISO 8601 in UTC with a Z suffix and exactly three fractional digits. */
export const UtcTimestampSchema = z.iso.datetime({ precision: 3 });

/** The header fields that every event carries, except `type`. */
export const envelopeHeaderShape = {
  protocolVersion: z.literal(PROTOCOL_VERSION),
  /** Generated by the emitter; the idempotency key. */
  id: EventIdSchema,
  /** Informational only. Ordering uses the server's receive time. */
  occurredAt: UtcTimestampSchema,
  /** The routing and security boundary. */
  workspaceId: WorkspaceIdSchema,
  actor: ActorSchema,
  /** null only for events that the server itself originates. */
  deviceId: DeviceIdSchema.nullable(),
  /** Groups one flow, for example one request and all its runs. A label, never used for lookups. */
  correlationId: CorrelationIdSchema.optional(),
  /** The event that directly caused this one. A label, never used for lookups. */
  causationId: EventIdSchema.optional(),
};

/** A run changed state. The transition must be allowed by `canTransition`. */
export const AgentRunStateChangedPayloadSchema = z
  .object({
    runId: RunIdSchema,
    agentId: AgentIdSchema,
    repositoryId: RepositoryIdSchema.optional(),
    /** null when the server creates the run. */
    previousState: RunStateSchema.nullable(),
    state: RunStateSchema,
    reason: displayText(LIMITS.runReason).optional(),
  })
  .superRefine((payload, ctx) => {
    if (!canTransition(payload.previousState, payload.state)) {
      ctx.addIssue({
        code: "custom",
        message: "Illegal run state transition",
        path: ["state"],
      });
    }
  });
export type AgentRunStateChangedPayload = z.infer<
  typeof AgentRunStateChangedPayloadSchema
>;

export const AgentRunStateChangedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("agent.run.state_changed"),
  payload: AgentRunStateChangedPayloadSchema,
});
export type AgentRunStateChangedEvent = z.infer<
  typeof AgentRunStateChangedEventSchema
>;

/**
 * Every protocol v0 event. Named `ProtocolEvent`, not `Event`, so that it
 * does not shadow the DOM `Event` type in the desktop renderer.
 */
export const ProtocolEventSchema = z.discriminatedUnion("type", [
  AgentRunStateChangedEventSchema,
]);
export type ProtocolEvent = z.infer<typeof ProtocolEventSchema>;

export type EventType = ProtocolEvent["type"];

/** The event types of this protocol version, taken from `ProtocolEventSchema`. */
export const EVENT_TYPES: readonly EventType[] = Object.freeze(
  ProtocolEventSchema.options.map((schema) => schema.shape.type.value),
);

/** Actor rules that hold in every direction. */
export function actorAllowed(event: ProtocolEvent): boolean {
  switch (event.type) {
    case "agent.run.state_changed":
      // The server (system) creates runs; afterwards only the run's agent reports transitions.
      return (
        event.actor.kind === "system" ||
        (event.actor.kind === "agent" &&
          event.actor.agentId === event.payload.agentId)
      );
  }
}
