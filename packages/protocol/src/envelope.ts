import * as z from "zod";
import { MemberRoleSchema, WorkspaceMemberSchema } from "./account.ts";
import {
  ChatMessageSchema,
  displayText,
  multilineText,
  ProjectSchema,
  RunStateSchema,
  UtcTimestampSchema,
} from "./entities.ts";
import {
  AgentIdSchema,
  CorrelationIdSchema,
  DeviceIdSchema,
  EventIdSchema,
  MemberIdSchema,
  ProjectIdSchema,
  RepositoryIdSchema,
  RunIdSchema,
  UserIdSchema,
  WorkspaceIdSchema,
} from "./ids.ts";
import { canTransition, LIMITS, PROTOCOL_VERSION } from "./model.ts";

/**
 * Who caused an event. A client cannot choose its identity: the server binds
 * the actor to the authenticated connection before it relays or stores an
 * event (from M2), and only the server itself acts as `system`.
 */
export const ActorSchema = z.discriminatedUnion("kind", [
  z.object({ kind: z.literal("user"), userId: UserIdSchema }),
  z.object({ kind: z.literal("agent"), agentId: AgentIdSchema }),
  z.object({ kind: z.literal("system") }),
]);
export type Actor = z.infer<typeof ActorSchema>;

/**
 * The header fields that every event carries, except `type`. Frozen, so that
 * no code can replace a field schema of a schema built from it later.
 */
export const envelopeHeaderShape = Object.freeze({
  protocolVersion: z.literal(PROTOCOL_VERSION),
  /** Generated by the emitter; the idempotency key. */
  id: EventIdSchema,
  /** Informational only. Ordering uses the server's receive time. */
  occurredAt: UtcTimestampSchema,
  /** The routing and security boundary. */
  workspaceId: WorkspaceIdSchema,
  actor: ActorSchema,
  /** null only for events that the server itself originates. */
  deviceId: DeviceIdSchema.nullable(),
  /** Groups one flow, for example one request and all its runs. A label, never used for lookups. */
  correlationId: CorrelationIdSchema.optional(),
  /** The event that directly caused this one. A label, never used for lookups. */
  causationId: EventIdSchema.optional(),
});

/** A run changed state. The transition must be allowed by `canTransition`. */
export const AgentRunStateChangedPayloadSchema = z
  .object({
    runId: RunIdSchema,
    agentId: AgentIdSchema,
    repositoryId: RepositoryIdSchema.optional(),
    /** null when the server creates the run. */
    previousState: RunStateSchema.nullable(),
    state: RunStateSchema,
    reason: displayText(LIMITS.runReason).optional(),
  })
  .superRefine((payload, ctx) => {
    if (!canTransition(payload.previousState, payload.state)) {
      ctx.addIssue({
        code: "custom",
        message: "Illegal run state transition",
        path: ["state"],
      });
    }
  });
export type AgentRunStateChangedPayload = z.infer<
  typeof AgentRunStateChangedPayloadSchema
>;

export const AgentRunStateChangedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("agent.run.state_changed"),
  payload: AgentRunStateChangedPayloadSchema,
});
export type AgentRunStateChangedEvent = z.infer<
  typeof AgentRunStateChangedEventSchema
>;

// Membership events (ADR 0014, "Protocol"): the changes that every member of
// a workspace must see. Only the server originates them, with a `system`
// actor and `deviceId: null` (see `actorAllowed`).

/** Checks that the event's person belongs to its workspace and passes `check`. */
function memberInWorkspace(
  check: (member: z.infer<typeof WorkspaceMemberSchema>) => boolean,
  message: string,
) {
  return (
    event: {
      workspaceId: string;
      payload: { member: z.infer<typeof WorkspaceMemberSchema> };
    },
    ctx: z.RefinementCtx,
  ) => {
    if (event.payload.member.workspaceId !== event.workspaceId) {
      ctx.addIssue({
        code: "custom",
        message: "The person belongs to another workspace",
        path: ["payload", "member", "workspaceId"],
      });
    }
    if (!check(event.payload.member)) {
      ctx.addIssue({ code: "custom", message, path: ["payload", "member"] });
    }
  };
}

/** The owner or an admin defined a person, who is unclaimed. */
export const WorkspaceMemberDefinedEventSchema = z
  .object({
    ...envelopeHeaderShape,
    type: z.literal("workspace.member.defined"),
    payload: z.object({ member: WorkspaceMemberSchema }),
  })
  .superRefine(
    memberInWorkspace(
      (member) => member.userId === null && member.removedAt === null,
      "A defined person is unclaimed and active",
    ),
  );

/** An account claimed a person, through an invitation or an approved join request. */
export const WorkspaceMemberClaimedEventSchema = z
  .object({
    ...envelopeHeaderShape,
    type: z.literal("workspace.member.claimed"),
    payload: z.object({ member: WorkspaceMemberSchema }),
  })
  .superRefine(
    memberInWorkspace(
      (member) =>
        member.userId !== null &&
        member.removedAt === null &&
        member.role === "member",
      "A claimed person has an account, is active, and is a member",
    ),
  );

/** A person's display name changed. */
export const WorkspaceMemberRenamedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("workspace.member.renamed"),
  payload: z.object({
    memberId: MemberIdSchema,
    displayName: displayText(LIMITS.displayName),
  }),
});

/** A person was removed or left. Nothing is deleted; the person stays as a former member. */
export const WorkspaceMemberRemovedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("workspace.member.removed"),
  payload: z.object({
    memberId: MemberIdSchema,
    removedAt: UtcTimestampSchema,
  }),
});

/** A person became an admin, or a member again. The owner changes only by transfer. */
export const WorkspaceMemberRoleChangedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("workspace.member.role_changed"),
  payload: z.object({
    memberId: MemberIdSchema,
    role: MemberRoleSchema.exclude(["owner"]),
  }),
});

/**
 * Ownership moved in one transaction: the previous owner is now an admin,
 * and the target is the owner.
 */
export const WorkspaceOwnershipTransferredEventSchema = z
  .object({
    ...envelopeHeaderShape,
    type: z.literal("workspace.ownership.transferred"),
    payload: z.object({
      previousOwnerMemberId: MemberIdSchema,
      ownerMemberId: MemberIdSchema,
    }),
  })
  .superRefine((event, ctx) => {
    if (event.payload.previousOwnerMemberId === event.payload.ownerMemberId) {
      ctx.addIssue({
        code: "custom",
        message: "Ownership moves to another person",
        path: ["payload", "ownerMemberId"],
      });
    }
  });

// Project events (#155): the projects of a workspace, which every member
// sees. Only the server originates them, after the commit, with a `system`
// actor and `deviceId: null`, like the membership events (see `actorAllowed`).

/** A member created a project, together with its project chat. */
export const WorkspaceProjectCreatedEventSchema = z
  .object({
    ...envelopeHeaderShape,
    type: z.literal("workspace.project.created"),
    payload: z.object({ project: ProjectSchema }),
  })
  .superRefine((event, ctx) => {
    if (event.payload.project.workspaceId !== event.workspaceId) {
      ctx.addIssue({
        code: "custom",
        message: "The project belongs to another workspace",
        path: ["payload", "project", "workspaceId"],
      });
    }
  });

/** A project's name changed. */
export const WorkspaceProjectRenamedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("workspace.project.renamed"),
  payload: z.object({
    projectId: ProjectIdSchema,
    name: displayText(LIMITS.name),
  }),
});

// Chat events (#110). A project's chat has one stream of messages; the
// events name the project, and the server finds the conversation that holds
// it. Storing messages and the history route belong to #27.

/**
 * A person asks the server to post a message to a project's chat. Only a
 * device sends it, with the person's `user` actor and its own device; the
 * server binds both to the connection (ADR 0006) and never relays this
 * event. It is a request that the server may refuse, so its name is not in
 * the past tense; the fact is `chat.message.created`. The event ID is the
 * idempotency key: a resent event with the same ID creates no second message.
 */
export const ChatMessageSendEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("chat.message.send"),
  payload: z.object({
    projectId: ProjectIdSchema,
    body: multilineText(LIMITS.messageBody),
  }),
});
export type ChatMessageSendEvent = z.infer<typeof ChatMessageSendEventSchema>;

/**
 * The server stored a chat message and sends it to every connection
 * subscribed to the workspace, the sender's included. Only the server
 * originates it, with a `system` actor and `deviceId: null`; the null device
 * keeps the sender's device ID from other members. The message is always
 * attributed to its author, `payload.message.authorMemberId`.
 * The server sets `causationId` to the ID of the `chat.message.send` that
 * the message came from, so the sending device can replace its pending copy.
 */
export const ChatMessageCreatedEventSchema = z.object({
  ...envelopeHeaderShape,
  type: z.literal("chat.message.created"),
  payload: z.object({ message: ChatMessageSchema }),
});
export type ChatMessageCreatedEvent = z.infer<
  typeof ChatMessageCreatedEventSchema
>;

/**
 * Every protocol v0 event. Named `ProtocolEvent`, not `Event`, so that it
 * does not shadow the DOM `Event` type in the desktop renderer.
 */
export const ProtocolEventSchema = z.discriminatedUnion("type", [
  AgentRunStateChangedEventSchema,
  WorkspaceMemberDefinedEventSchema,
  WorkspaceMemberClaimedEventSchema,
  WorkspaceMemberRenamedEventSchema,
  WorkspaceMemberRemovedEventSchema,
  WorkspaceMemberRoleChangedEventSchema,
  WorkspaceOwnershipTransferredEventSchema,
  WorkspaceProjectCreatedEventSchema,
  WorkspaceProjectRenamedEventSchema,
  ChatMessageSendEventSchema,
  ChatMessageCreatedEventSchema,
]);
export type ProtocolEvent = z.infer<typeof ProtocolEventSchema>;

export type EventType = ProtocolEvent["type"];

/** Event types that only the server originates. A device never sends them. */
export const SERVER_ONLY_EVENT_TYPES = Object.freeze([
  "workspace.member.defined",
  "workspace.member.claimed",
  "workspace.member.renamed",
  "workspace.member.removed",
  "workspace.member.role_changed",
  "workspace.ownership.transferred",
  "workspace.project.created",
  "workspace.project.renamed",
  "chat.message.created",
] as const satisfies readonly EventType[]);
export type ServerOnlyEventType = (typeof SERVER_ONLY_EVENT_TYPES)[number];

/**
 * Event types that only a device sends. The server never relays them, so a
 * device refuses them from the server (`decodeServerMessage`).
 */
export const CLIENT_ONLY_EVENT_TYPES = Object.freeze([
  "chat.message.send",
] as const satisfies readonly EventType[]);
export type ClientOnlyEventType = (typeof CLIENT_ONLY_EVENT_TYPES)[number];

/** The event types of this protocol version, taken from `ProtocolEventSchema`. */
export const EVENT_TYPES: readonly EventType[] = Object.freeze(
  ProtocolEventSchema.options.map((schema) => schema.shape.type.value),
);

/** Actor rules that hold in every direction. */
export function actorAllowed(event: ProtocolEvent): boolean {
  switch (event.type) {
    case "agent.run.state_changed":
      // The server (system) creates runs; afterwards only the run's agent reports transitions.
      return (
        event.actor.kind === "system" ||
        (event.actor.kind === "agent" &&
          event.actor.agentId === event.payload.agentId)
      );
    case "workspace.member.defined":
    case "workspace.member.claimed":
    case "workspace.member.renamed":
    case "workspace.member.removed":
    case "workspace.member.role_changed":
    case "workspace.ownership.transferred":
    case "workspace.project.created":
    case "workspace.project.renamed":
    case "chat.message.created":
      // Only the server reports membership and project changes and stored messages.
      return event.actor.kind === "system" && event.deviceId === null;
    case "chat.message.send":
      // A person sends from one of their devices; identity binding checks both.
      return event.actor.kind === "user" && event.deviceId !== null;
  }
}
